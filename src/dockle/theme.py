def _portal_version(version: str) -> str:
    return f" <span>{escape(version)}</span>" if version else ""


def _portal_repository(repository: str) -> str:
    if not repository:
        return ""
    return (
        '    <p class="dockle-portal-repository">'
        f'<a href="{escape(repository)}">Source repository'
        '<i data-lucide="external-link" aria-hidden="true"></i>'
        "</a></p>\n"
    )


def _portal_logo(asset: Path | str | None) -> str:
    if asset is None:
        return ""
    return (
        '      <img class="dockle-portal-logo" '
        f'src="{escape(_portal_asset_url(asset))}" alt="">\n'
    )


def _portal_favicon(asset: Path | str | None) -> str:
    if asset is None:
        return ""
    return (
        f'  <link rel="icon" href="{escape(_portal_asset_url(asset))}" '
        "data-dockle-favicon>\n"
    )


def _portal_asset_url(asset: Path | str) -> str:
    return asset if isinstance(asset, str) else f"_dockle/{asset.name}"


def _portal_project_docs(home: Path | None) -> str:
    if home is None:
        return ""
    source = home.read_text(encoding="utf-8")
    return (
        '    <article class="dockle-portal-docs">\n'
        f"{render_markdown(source)}\n"
        "    </article>\n"
    )


def _portal_cards(
    targets: tuple[TargetConfig, ...], output: Path
) -> str:
    """Render the shared comparison cards for portal or Sphinx home pages."""

    cards: list[str] = []
    for target in targets:
        relative = _target_href(target, output)
        description = target.description or (
            f"Documentation generated with {target.framework}."
        )
        cards.append(
            f"""      <a class="dockle-portal-card" href="{escape(relative)}">
        <span class="dockle-portal-framework">{escape(target.framework)}</span>
        <strong>{escape(target.title)}</strong>
        <span>{escape(description)}</span>
      </a>"""
        )
    return "\n".join(cards)


def _target_href(target: TargetConfig, output: Path) -> str:
    relative = target.output.relative_to(output).as_posix()
    if target.framework == "rustdoc" and target.output.is_dir():
        crates = sorted(
            path
            for path in target.output.iterdir()
            if path.is_dir() and (path / _INDEX_FILE).is_file()
        )
        if len(crates) == 1:
            return f"{relative}/{crates[0].name}/"
    return f"{relative}/"
